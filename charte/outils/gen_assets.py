"""Regenerates the embedded assets of the KDX-style UI (run from this folder).

    python gen_assets.py                ../fonts.css, ../icons.js

Outputs are committed: the build itself never runs Python.
  fonts.css               KIRC Pixel and KIRC Pixel Log (tools/gen_font.py) as base64 @font-face
  icons.js                the pixel icons of tools/pixel_icons.py as SVG strings
"""
import base64
import struct
import sys
import zlib
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import pixel_icons  # noqa: E402

import gen_font  # noqa: E402


def b64(data):
    return base64.b64encode(data).decode()


def fonts_css():
    faces = []
    for family in gen_font.FACES:
        faces.append(f"@font-face {{ font-family: '{family}'; font-style: normal; font-weight: 100 900;\n"
                     f"  src: url(data:font/woff2;base64,{b64(gen_font.to_bytes(family, 'woff2'))}) format('woff2'); }}\n")
    return ("/* Generated by tools/gen_assets.py from tools/gen_font.py -- the two bitmap fonts of the UI (interface and\n"
            "   transcript), whole-pixel outlines: one font pixel is one CSS pixel at font-size 14px. */\n" + "".join(faces))


def icons_js():
    out = ["// Generated by tools/gen_assets.py from tools/pixel_icons.py -- do not edit.",
           "// 16x16 pixel icons, SVG strings. pix(name, size) -> markup; fillPix() fills every [data-ic].",
           "const PIX = {"]
    for name, svg in pixel_icons.all_svgs().items():
        out.append(f"  {name}: '{svg}',")
    out.append("};")
    out.append('''const pix = (name, size = 16) =>
  (PIX[name] || PIX.serveur).replace('width="16" height="16"', `width="${size}" height="${size}"`);
const fillPix = (scope = document) => scope.querySelectorAll("[data-ic]").forEach(el => {
  el.innerHTML = pix(el.dataset.ic, +el.dataset.size || 16);
});
''')
    return "\n".join(out)


def png(path, pixels, scale):
    """Writes the 16x16 icon scaled by `scale` (nearest neighbour) as an RGBA PNG."""
    size = 16 * scale
    raw = bytearray()
    for y in range(size):
        raw.append(0)
        for x in range(size):
            c = pixels.get((x // scale, y // scale))
            if c is None:
                raw += b'\0\0\0\0'
            else:
                h = pixel_icons.PAL[c].lstrip('#')
                raw += bytes(int(h[i:i + 2], 16) for i in (0, 2, 4)) + b'\xff'

    def chunk(tag, data):
        body = tag + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body) & 0xffffffff)

    data = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(bytes(raw), 9)) + chunk(b'IEND', b''))
    path.write_bytes(data)


(root / 'fonts.css').write_text(fonts_css(), encoding='utf-8')
(root / 'icons.js').write_text(icons_js(), encoding='utf-8')
for n in ('fonts.css', 'icons.js'):
    print(n, (root / n).stat().st_size)
