"""Generates ui/themes.css (run from the repo root):  python tools/gen_themes.py

KDX's own appearance files for a single accent colour (the "Electric ..." family, Amber CRT, Mach
Teal, Charcoal in ProfDrLuigi/Haxial-KDX) differ by one hue: a ramp of that colour, from a light tint
to dark shades. The default look is the red one, whose ramp is measured on KDX itself:

    frame #cc0000 / #880000 / #440000, title #320000 -> #c30000, bar #e83c3c / #c01010 / #8a0202

In HSV terms that ramp is value .80 / .53 / .27, title .20 -> .77, bar (s .74 v .91) (s .92 v .75)
(s .99 v .54). The other themes apply the same ramp to another hue. Text fields keep a "console ink"
of their own, and the selected-row colours follow the hue. The default theme needs no override: it is
what theme.css already says.
"""
import colorsys
from pathlib import Path

# id, French name, hue (degrees), saturation, lift (value multiplier, for hues that read dark),
# console ink, selected row (background, text)
THEMES = [
    ("bleu", "Bleu électrique", 240, 1.0, 1.25, "#8fd0ff", "#001177", "#ff00ff"),
    ("vert", "Vert électrique", 120, 1.0, 1.0, "#00ff00", "#004422", "#ffff00"),
    ("violet", "Violet électrique", 300, 1.0, 1.1, "#ffa8ff", "#2a0044", "#00ffff"),
    ("ambre", "Ambre CRT", 20, 0.98, 1.0, "#ffb04a", "#3a1800", "#ffe090"),
    ("sarcelle", "Sarcelle", 180, 0.5, 1.15, "#a8fff0", "#003a3a", "#ffffff"),
    ("charbon", "Charbon", 0, 0.0, 1.0, "#e6e6e6", "#444444", "#ffffff"),
]


def hexcolor(h, s, v):
    r, g, b = colorsys.hsv_to_rgb((h % 360) / 360, max(0, min(1, s)), max(0, min(1, v)))
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def block(tid, h, s, lift, ink, sel_bg, sel_fg):
    def c(sat, val):
        return hexcolor(h, s * sat, min(1, val * lift))

    edge, mid, dark, hover = c(1, .80), c(1, .533), c(1, .267), c(1, .40)
    tfrom, tto = c(1, .196), c(1, .765)
    top, bmid, bot = c(.74, .91), c(.92, .75), c(.99, .54)
    spark, accent = c(.55, 1.0), c(.89, .83)
    r, g, b = (int(accent[i:i + 2], 16) for i in (1, 3, 5))
    return f"""html[data-theme="{tid}"] {{
  --a-edge: {edge}; --a-mid: {mid}; --a-dark: {dark}; --a-hover: {hover};
  --a-title-from: {tfrom}; --a-title-to: {tto};
  --bar-top: {top}; --bar-mid: {bmid}; --bar-bot: {bot}; --a-spark: {spark};
  --accent: {accent}; --accent-rgb: {r}, {g}, {b};
  --field-ink: {ink}; --sel-bg: {sel_bg}; --sel-fg: {sel_fg};
}}
"""


def main():
    out = ["/* Generated by tools/gen_themes.py -- do not edit. One accent ramp per theme (see that file). */\n"]
    for tid, _name, h, s, lift, ink, sb, sf in THEMES:
        out.append(block(tid, h, s, lift, ink, sb, sf))
    Path(__file__).resolve().parent.parent.joinpath("ui", "themes.css").write_text("\n".join(out), encoding="utf-8")
    print(len(THEMES), "themes")


if __name__ == "__main__":
    main()
